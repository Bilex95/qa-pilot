"""Generate frontend/src/app/globals.css from the locked prototype (D-043).

Run from the repo root: python scripts/build_globals_css.py [--check]
--check exits 1 when the committed file differs from what would be generated (used in CI).

Prototype only UI (the dev toolbar and the "View as" role switcher) is removed selector by selector:
a rule that also styles real components keeps its other selectors (the Stage 3 bug was dropping whole
lines, which removed the 44 px input rule because it also listed `.role-switch select`).
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "design" / "reference" / "approved.html"
OUT = ROOT / "frontend" / "src" / "app" / "globals.css"
PROTOTYPE_ONLY = re.compile(r"\.devbar|\.role-switch|\.rs-label|body\.clean")


def strip_prototype_selectors(css: str) -> str:
    out: list[str] = []
    for rule in re.split(r"(?<=\})", css):
        m = re.match(r"(\s*)([^{}@]+?)(\s*\{[^{}]*\})\s*$", rule, re.S)
        if not m or not PROTOTYPE_ONLY.search(m.group(2)):
            out.append(rule)
            continue
        kept = [s.strip() for s in m.group(2).split(",") if not PROTOTYPE_ONLY.search(s)]
        if kept:
            out.append(f"{m.group(1)}{', '.join(kept)}{m.group(3)}")
    return "".join(out)


def build() -> str:
    html = SRC.read_text(encoding="utf-8")
    css = html.split("<style>", 1)[1].split("</style>", 1)[0]
    root_match = re.search(r":root \{(.*?)\n\}", css, re.S)
    assert root_match, "no :root block in the prototype"
    root = root_match.group(1)
    rest = css[root_match.end():]
    rest = re.sub(r"\n/\* Prototype dev toolbar.*?(?=\n/\* =)", "\n", rest, flags=re.S)
    rest = strip_prototype_selectors(rest)
    assert not PROTOTYPE_ONLY.search(rest), "prototype only selectors left"
    root = root.replace('--font-ui: "Atkinson Hyperlegible",', '--font-ui: var(--font-atkinson), "Atkinson Hyperlegible",')
    root = root.replace('--font-mono: "IBM Plex Mono",', '--font-mono: var(--font-plex-mono), "IBM Plex Mono",')
    tokens = re.findall(r"--([a-z0-9-]+):", root)
    skip = ("font", "fs-", "lh-", "fw-", "sp-", "r-", "shadow", "sidebar-w", "header-h", "content-max", "focus")
    colours = [t for t in tokens if not t.startswith(skip)]
    theme = ["@theme inline {", *[f"  --color-{t}: var(--{t});" for t in colours],
             "  --font-sans: var(--font-ui);", "  --font-mono: var(--font-mono);",
             "  --radius-sm: var(--r-sm);", "  --radius-md: var(--r-md);", "  --radius-lg: var(--r-lg);",
             "  --shadow-float: var(--shadow-float);", "}"]
    return (
        "/* QA Pilot styles. Generated by scripts/build_globals_css.py from the locked prototype\n"
        "   design/reference/approved.html (D-043). Tokens: design/TOKENS.md. Do not edit by hand. */\n"
        '@import "tailwindcss";\n\n'
        f":root {{{root}\n}}\n\n"
        "/* Tokens as Tailwind theme values: bg-primary, text-ink-3, border-line, font-mono ... */\n"
        + "\n".join(theme) + "\n\n"
        f"@layer components {{\n{rest.strip()}\n}}\n"
    )


if __name__ == "__main__":
    css = build()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT.exists() else ""
        if current != css:
            print("globals.css is out of date: run python scripts/build_globals_css.py")
            sys.exit(1)
        print("globals.css matches the prototype")
        sys.exit(0)
    OUT.write_text(css, encoding="utf-8", newline="\n")
    print(f"Wrote {OUT.relative_to(ROOT)} ({len(css.splitlines())} lines)")
