// Captures the locked design screenshots from design/reference/approved.html.
// File names come from docs/requirements/SCREEN_INVENTORY.md section 3, so the
// inventory and the images cannot drift apart.
// Usage (from e2e/): node scripts/capture-design.mjs [slugFilter]
import { chromium } from 'playwright';
import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const html = pathToFileURL(resolve(root, 'design/reference/approved.html')).href;
const outDir = resolve(root, 'design/screenshots');
const filter = process.argv[2];

// slug -> route, role used for the capture, optional per state route override
export const SCREENS = {
  login: { route: '/login' },
  register: { route: '/register' },
  'org-setup': { route: '/onboarding/org' },
  invite: { route: '/invite/k7Qm2vX9pL4w' },
  dashboard: { route: '/o/lumen/dashboard' },
  projects: { route: '/o/lumen/projects' },
  'project-overview': { route: '/o/lumen/projects/WEB' },
  'bug-list': { route: '/o/lumen/bugs' },
  board: { route: '/o/lumen/board' },
  'bug-detail': { route: '/o/lumen/bugs/WEB-142' },
  'bug-new': { route: '/o/lumen/bugs/new', role: 'qa_engineer' },
  'test-suites': { route: '/o/lumen/tests' },
  'test-case-editor': { route: '/o/lumen/tests/cases/TC-103', states: { ai: '/o/lumen/tests/cases/new' } },
  'test-runs': { route: '/o/lumen/runs' },
  'test-run': { route: '/o/lumen/runs/R-31' },
  releases: { route: '/o/lumen/releases' },
  'release-detail': { route: '/o/lumen/releases/r1' },
  reports: { route: '/o/lumen/reports' },
  members: { route: '/o/lumen/members', role: 'org_admin' },
  settings: { route: '/o/lumen/settings', role: 'org_admin' },
  'ai-usage': { route: '/o/lumen/ai-usage', role: 'org_admin' },
  'not-found': { route: '/o/lumen/this-page-does-not-exist' },
};
const VIEWPORTS = { desktop: { width: 1440, height: 900 }, mobile: { width: 390, height: 844 } };

function plannedFiles() {
  const inv = readFileSync(resolve(root, 'docs/requirements/SCREEN_INVENTORY.md'), 'utf8');
  const files = [...inv.matchAll(/`([a-z0-9-]+-(?:desktop|mobile)\.png)`/g)].map(m => m[1]);
  return [...new Set(files)].map(f => {
    const base = f.replace(/\.png$/, '');
    const viewport = base.endsWith('-desktop') ? 'desktop' : 'mobile';
    const rest = base.slice(0, -(viewport.length + 1));
    const slug = Object.keys(SCREENS).sort((a, b) => b.length - a.length).find(s => rest.startsWith(s + '-'));
    if (!slug) throw new Error(`No screen mapping for ${f}`);
    return { file: f, slug, state: rest.slice(slug.length + 1), viewport };
  });
}

const shots = plannedFiles().filter(s => !filter || s.slug === filter);
if (!filter) { rmSync(outDir, { recursive: true, force: true }); }
mkdirSync(outDir, { recursive: true });
const browser = await chromium.launch();
const problems = [];
for (const vp of Object.keys(VIEWPORTS)) {
  const ctx = await browser.newContext({ viewport: VIEWPORTS[vp], deviceScaleFactor: 1, reducedMotion: 'reduce' });
  const page = await ctx.newPage();
  page.on('pageerror', e => problems.push(`page error: ${e.message}`));
  page.on('console', m => { if (m.type() === 'error') problems.push(`console error: ${m.text()}`); });
  for (const s of shots.filter(x => x.viewport === vp)) {
    const cfg = SCREENS[s.slug];
    const route = (cfg.states && cfg.states[s.state]) || cfg.route;
    const params = new URLSearchParams({ role: cfg.role || 'qa_lead', clean: '1' });
    if (s.state !== 'default') params.set('state', s.state);
    await page.goto(`${html}#${route}?${params}`);
    await page.evaluate(() => document.fonts.ready);
    await page.waitForTimeout(150);
    await page.screenshot({ path: resolve(outDir, s.file), animations: 'disabled' });
  }
  await ctx.close();
}
await browser.close();
console.log(`Captured ${shots.length} screenshots into design/screenshots`);

// Contact sheet: design/screenshots/INDEX.md, generated from the inventory
if (!filter) {
  const inv = readFileSync(resolve(root, 'docs/requirements/SCREEN_INVENTORY.md'), 'utf8');
  const rows = [...inv.matchAll(/^\| (SCR-\d+) \| ([^|]+) \| ([^|]+) \| ([^|]+) \| ([^|]+) \| ([^|]+) \| `([a-z-]+)` \|$/gm)]
    .map(m => ({ id: m[1], name: m[2].trim(), route: m[3].trim(), reqs: m[5].trim(), slug: m[7] }));
  const all = plannedFiles();
  let md = `# Design screenshots: contact sheet\n\nGenerated by \`e2e/scripts/capture-design.mjs\` from \`design/reference/approved.html\`. Desktop 1440x900, mobile 390x844. Do not edit by hand.\n\n`;
  md += `Captured as QA Lead unless noted. Prototype URL pattern: \`approved.html#<route>?role=<role>&state=<state>\`.\n\n`;
  md += `| Screen | Route captured | Role | Files |\n|---|---|---|---|\n`;
  for (const r of rows) {
    const cfg = SCREENS[r.slug];
    md += `| ${r.id} ${r.name} | \`${cfg.route}\` | ${cfg.role || 'qa_lead'} | ${all.filter(f => f.slug === r.slug).map(f => `[${f.state} ${f.viewport}](${f.file})`).join(', ')} |\n`;
  }
  md += `\n## Thumbnails\n`;
  for (const r of rows) {
    md += `\n### ${r.id} ${r.name}\n\n${r.reqs}\n\n`;
    for (const f of all.filter(x => x.slug === r.slug)) md += `<a href="${f.file}"><img src="${f.file}" alt="${r.name}, ${f.state}, ${f.viewport}" width="${f.viewport === 'desktop' ? 360 : 120}"></a>\n`;
  }
  writeFileSync(resolve(outDir, 'INDEX.md'), md);
  console.log(`Wrote design/screenshots/INDEX.md (${rows.length} screens)`);
}
if (problems.length) { console.error([...new Set(problems)].join('\n')); process.exit(1); }
